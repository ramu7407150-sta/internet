from fastapi import FastAPI
from pydantic import BaseModel, Field

app = FastAPI(title="API Магазина", description="Расчёт полной стоимости товара с налогом (в процентах)")

# Модель товара
class Товар(BaseModel):
    название: str = Field(..., title="Название товара")
    описание: str | None = Field(default=None, title="Описание товара", max_length=300)
    цена: float = Field(..., gt=0, title="Цена товара")
    налог: float | None = Field(default=0, title="Налог (%) на товар")

# Эндпоинт для обновления товара
@app.put("/товары/{id_товара}")
async def обновить_товар(id_товара: int, товар: Товар):
    # Расчёт полной цены с учётом процента налога
    налоговая_сумма = товар.цена * ((товар.налог or 0) / 100)
    полная_цена = товар.цена + налоговая_сумма

    результат = {
        "ID товара": id_товара,
        "Название": товар.название,
        "Цена без налога": товар.цена,
        "Налог (%)": товар.налог,
        "Полная цена (с налогом)": round(полная_цена, 2),
        "Описание": товар.описание
    }
    return результат
